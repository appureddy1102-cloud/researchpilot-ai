"""
STAGES 1 & 2 - Query analysis and research planning.

One LLM call (JSON mode) produces the analysis (topic, keywords, intent,
needs-current-info, sub-questions, 2-4 search queries) and the research plan
(objective, subtopics, information requirements, strategy, expected evidence,
limitations). If the LLM fails, a deterministic fallback plan is used so the
run can still continue - and the UI is told that happened.
"""
from __future__ import annotations

from datetime import date

from agent.llm import LLMError, parse_json
from tools.source_evaluator import keywords_from

PLANNER_PROMPT = """You are the planning module of a web research agent. Today's date is {today}.

Research question: "{question}"

Return ONLY a JSON object with exactly these keys:
{{
  "main_topic": "short topic phrase",
  "keywords": ["5-8 important keywords"],
  "intent": "one sentence: what the user really wants to know",
  "needs_current_info": true or false,
  "sub_questions": ["2-5 smaller research questions that together answer the main one"],
  "search_queries": ["2-4 distinct, specific web search queries (add the year {year} only if recency matters)"],
  "plan": {{
    "objective": "...",
    "subtopics": ["..."],
    "information_requirements": ["facts/data needed"],
    "search_strategy": "how you will search and which source types to prefer (government, universities, journals, official reports)",
    "expected_evidence": ["kinds of evidence expected"],
    "potential_limitations": ["what could make the answer incomplete or uncertain"]
  }}
}}"""


def _as_list(v) -> list[str]:
    if isinstance(v, str):
        return [v]
    return [str(x).strip() for x in v if str(x).strip()] if isinstance(v, list) else []


def fallback_plan(question: str, reason: str = "") -> dict:
    kws = keywords_from(question)[:8]
    year = date.today().year
    topic = " ".join(kws[:4]) or question[:50]
    queries = [question.strip().rstrip("?")[:200], f"{topic} overview evidence statistics {year}"]
    return {
        "main_topic": topic, "keywords": kws, "intent": f"Answer the question: {question}",
        "needs_current_info": any(w in question.lower() for w in ("latest", "recent", "current", "new", "today", str(year))),
        "sub_questions": [question], "search_queries": queries,
        "plan": {
            "objective": f"Find reliable, cited evidence to answer: {question}",
            "subtopics": kws[:4], "information_requirements": ["key facts", "statistics", "expert or institutional findings"],
            "search_strategy": "Run the planned queries, prefer government/university/journal sources.",
            "expected_evidence": ["institutional reports", "peer-reviewed or reputable publications"],
            "potential_limitations": ["Plan generated by rule-based fallback" + (f" ({reason})" if reason else "")],
        },
        "fallback": True,
    }


def analyze_and_plan(llm, question: str, max_queries: int = 4) -> dict:
    """Return the combined analysis + plan dict (always valid)."""
    today = date.today()
    try:
        msg = llm.chat([{"role": "user", "content": PLANNER_PROMPT.format(
            question=question, today=today.isoformat(), year=today.year)}], json_mode=True, temperature=0.2)
        data = parse_json(msg.content)
    except LLMError as e:
        return fallback_plan(question, str(e)[:80])
    if not isinstance(data, dict) or not _as_list(data.get("search_queries")):
        return fallback_plan(question, "planner returned invalid JSON")

    plan = data.get("plan") if isinstance(data.get("plan"), dict) else {}
    kws = _as_list(data.get("keywords")) or keywords_from(question)[:8]
    return {
        "main_topic": str(data.get("main_topic") or question[:60]),
        "keywords": [k.lower() for k in kws][:10],
        "intent": str(data.get("intent") or ""),
        "needs_current_info": bool(data.get("needs_current_info")),
        "sub_questions": _as_list(data.get("sub_questions"))[:5],
        "search_queries": _as_list(data.get("search_queries"))[:max(2, min(4, max_queries))],
        "plan": {
            "objective": str(plan.get("objective") or ""),
            "subtopics": _as_list(plan.get("subtopics")),
            "information_requirements": _as_list(plan.get("information_requirements")),
            "search_strategy": str(plan.get("search_strategy") or ""),
            "expected_evidence": _as_list(plan.get("expected_evidence")),
            "potential_limitations": _as_list(plan.get("potential_limitations")),
        },
        "fallback": False,
    }
